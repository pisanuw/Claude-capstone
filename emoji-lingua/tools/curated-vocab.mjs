/**
 * Hand-authored vocabulary layers that sit on top of the CLDR-derived data.
 *
 *  CURATED        the "obvious" choice for very common words, which beats
 *                 whatever CLDR scoring picks (e.g. cat -> 🐱, not 🐈).
 *  COMPOSED       abstract words with no literal emoji, approximated with one
 *                 or two evocative emoji. This is what lets ordinary prose
 *                 translate instead of passing through untouched.
 *  FUNCTION_WORDS glue words. Articles map to '' (dropped) so output reads
 *                 cleanly; the rest get a compact symbol.
 *
 * Format: newline-separated "word<space>emoji" pairs, parsed below.
 */

function parse(raw) {
  const out = {};
  for (const line of raw.trim().split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const i = t.indexOf(' ');
    if (i < 0) continue;
    out[t.slice(0, i)] = t.slice(i + 1).trim();
  }
  return out;
}

